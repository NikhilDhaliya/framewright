import type { PalmierApi, Unsubscribe } from '../shared/api'

const invoke = (channel: string, ...args: unknown[]) => ipcRenderer.invoke(channel, ...args)
const send = (channel: string, ...args: unknown[]) => ipcRenderer.send(channel, ...args)

function listen<T>(channel: string, cb: (value: T) => void): Unsubscribe {
  const handler = (_e: IpcRendererEvent, value: T) => cb(value)
  ipcRenderer.on(channel, handler)
  return () => ipcRenderer.removeListener(channel, handler)
}

