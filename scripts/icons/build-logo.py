# Builds the Framewright logo (app icon + "Framewright" wordmark, text outlined to paths so it renders
# without the font installed) from resources/icon.svg and Space Grotesk (OFL, resources/fonts/SpaceGrotesk).
# Writes resources/logo.svg (dark text, light backgrounds), resources/logo-dark.svg (white text, dark
# backgrounds) and resources/logo-mono.svg (currentColor text, used inline by the app).
#   python3 scripts/icons/build-logo.py
import io, re, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

root = Path(__file__).resolve().parents[2]
WORD, WEIGHT, SIZE = 'Framewright', 600, 520   # wordmark cap height ~ 0.7 * SIZE on a 1024 icon
TRACK = -0.02                                   # letter-spacing in em

font = TTFont(root / 'resources/fonts/SpaceGrotesk/SpaceGrotesk-Variable.ttf')
font = instantiateVariableFont(font, {'wght': WEIGHT})
upm = font['head'].unitsPerEm
cmap, gs, hmtx = font.getBestCmap(), font.getGlyphSet(), font['hmtx']
scale = SIZE / upm
cap = font['OS/2'].sCapHeight * scale

pen = SVGPathPen(gs)
x = 0.0
for ch in WORD:
    name = cmap[ord(ch)]
    # flip y (font units are y-up); baseline at y = 0
    gs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, 0)))
    x += hmtx[name][0] * scale + TRACK * SIZE
text_w = x - TRACK * SIZE
d = pen.getCommands()

icon = (root / 'resources/icon.svg').read_text()
body = re.search(r'<svg[^>]*>(.*)</svg>', icon, re.S).group(1)
body = re.sub(r'<!--.*?-->', '', body, flags=re.S)
body = body.replace('id="fw-', 'id="fwl-').replace('url(#fw-', 'url(#fwl-')

# icon occupies 64..960 of its 1024 box; place it at the left, wordmark vertically centred on it
gap = 80
tx = 960 + gap
ty = 512 + cap / 2
W, H = int(tx + text_w + 64), 1024

def svg(fill):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W // 4}" height="{H // 4}">\n'
            f'  <!-- Framewright logo (original artwork, GPL-3.0-only). Generated by scripts/icons/build-logo.py; '
            f'wordmark: Space Grotesk (SIL OFL 1.1). -->\n'
            f'  <title>Framewright</title>\n'
            f'  <g>{body}</g>\n'
            f'  <path transform="translate({tx:.1f} {ty:.1f})" fill="{fill}" d="{d}"/>\n</svg>\n')

(root / 'resources/logo.svg').write_text(svg('#1B1E3A'))
(root / 'resources/logo-dark.svg').write_text(svg('#FFFFFF'))
(root / 'resources/logo-mono.svg').write_text(svg('currentColor'))
print(f'logo {W}x{H}, wordmark {text_w:.0f}px')
